// Creating temperature variable
let temperature = 25;

// if, else if , and else statements
if(temperature < 0){
    console.log("Very cold")
}else if(temperature >= 0 && temperature <= 15){
    console.log("Cold")
}else if(temperature > 15 && temperature <= 25){
    console.log("Warm")
}else{
    console.log("Hot")
}